def tr(text, font="press"):
    if not isinstance(text, str) or not text:
        return text
    lang = get_lang()
    if lang == "es":
        return text
    mp = EN_MAP if lang == "en" else (PT_MAP if lang == "pt" else {})
    if text in mp:
        return mp[text]
    m_ch = re.match(r"^CAPÍTULO\s+(\d+)$", text)
    if m_ch:
        return f"CHAPTER {m_ch.group(1)}" if lang == "en" else f"CAPÍTULO {m_ch.group(1)}"
    m_c2 = re.match(r"^CHIPS EN LA PLACA:\s*(\d+)$", text)
    if m_c2:
        return f"CHIPS ON BOARD: {m_c2.group(1)}" if lang == "en" else f"CHIPS NA PLACA: {m_c2.group(1)}"
    return text
