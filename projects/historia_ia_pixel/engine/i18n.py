def tr(text, fname="press"):
    if not isinstance(text, str) or LANG == "es":
        return text

    # Caso especial: dos líneas "INTELIGENCIA" / "ARTIFICIAL" en fuente "press"
    # (en ch03 Lighthill cover ya dice "ARTIFICIAL" / "INTELLIGENCE" en fuente "silk")
    if LANG == "en" and fname == "press":
        if text == "INTELIGENCIA":
            return "ARTIFICIAL"
        if text == "ARTIFICIAL":
            return "INTELLIGENCE"

    table = EN_MAP if LANG == "en" else PT_MAP
    if text in table:
        return table[text]

    # Patrones dinámicos
    m = re.match(r"^CAPÍTULO (\d+)$", text)
    if m:
        return f"CHAPTER {m.group(1)}" if LANG == "en" else f"CAPÍTULO {m.group(1)}"

    m = re.match(r"^PLAZO: (\d+) VERANOS$", text)
    if m:
        return f"TIME: {m.group(1)} SUMMERS" if LANG == "en" else f"PRAZO: {m.group(1)} VERÕES"

    m = re.match(r"^~(\d+) MILLONES$", text)
    if m:
        return f"~{m.group(1)} MILLION" if LANG == "en" else f"~{m.group(1)} MILHÕES"

    m = re.match(r"^(\d+) AÑOS$", text)
    if m:
        return f"{m.group(1)} YEARS" if LANG == "en" else f"{m.group(1)} ANOS"

    m = re.match(r"^P([1-5])$", text)
    if m:
        return f"G{m.group(1)}" if LANG == "en" else text

    m = re.match(r"^DÍA ([1-5])$", text)
    if m:
        return f"DAY {m.group(1)}" if LANG == "en" else f"DIA {m.group(1)}"

    m = re.match(r"^MES ([1-2])$", text)
    if m:
        return f"MO. {m.group(1)}" if LANG == "en" else f"MÊS {m.group(1)}"

    if LANG == "en":
        # Porcentajes con coma decimal -> punto decimal (ej. "15,3 %" -> "15.3 %")
        m = re.match(r"^(\d+),(\d+) %$", text)
        if m:
            return f"{m.group(1)}.{m.group(2)} %"
        # Números con separador de miles '.' -> ',' (ej. "1.000.000" -> "1,000,000")
        if re.match(r"^\d{1,3}(\.\d{3})+$", text):
            return text.replace(".", ",")

    return text
