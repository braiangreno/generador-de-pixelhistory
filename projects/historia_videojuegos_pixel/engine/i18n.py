def tr(text, fname="press"):
    if not isinstance(text, str) or LANG == "es":
        return text

    table = EN_MAP if LANG == "en" else PT_MAP
    if text in table:
        return table[text]

    # Patrones dinámicos (contadores animados, porcentajes, capítulos)
    m = re.match(r"^CAPÍTULO (\d+)$", text)
    if m:
        return f"CHAPTER {m.group(1)}" if LANG == "en" else f"CAPÍTULO {m.group(1)}"

    m = re.match(r"^AÑO:\s*(.+)$", text)
    if m:
        return f"YEAR: {m.group(1)}" if LANG == "en" else f"ANO: {m.group(1)}"

    m = re.match(r"^\+?([\d.,]+)\s+MILLONES DE COPIAS$", text)
    if m:
        prefix = "+" if text.startswith("+") else ""
        val = m.group(1).replace(",", ".") if LANG == "en" else m.group(1)
        return f"{prefix}{val} MILLION COPIES" if LANG == "en" else f"{prefix}{val} MILHÕES DE CÓPIAS"

    m = re.match(r"^\+?([\d.,]+)\s+MILLONES DE CONSOLAS$", text)
    if m:
        prefix = "+" if text.startswith("+") else ""
        val = m.group(1).replace(",", ".") if LANG == "en" else m.group(1)
        return f"{prefix}{val} MILLION CONSOLES" if LANG == "en" else f"{prefix}{val} MILHÕES DE CONSOLES"

    m = re.match(r"^\+?([\d.,]+)\s+MILLONES$", text)
    if m:
        prefix = "+" if text.startswith("+") else ""
        val = m.group(1).replace(",", ".") if LANG == "en" else m.group(1)
        return f"{prefix}{val} MILLION" if LANG == "en" else f"{prefix}{val} MILHÕES"

    m = re.match(r"^SWITCH · ([\d.,]+) MILLONES$", text)
    if m:
        return f"SWITCH · {m.group(1)} MILLION" if LANG == "en" else f"SWITCH · {m.group(1)} MILHÕES"

    m = re.match(r"^PS2 · ([\d.,]+) MILLONES$", text)
    if m:
        return f"PS2 · {m.group(1)} MILLION" if LANG == "en" else f"PS2 · {m.group(1)} MILHÕES"

    m = re.match(r"^SUPER MARIO BROS\. · \+([\d.,]+) MILLONES$", text)
    if m:
        return f"SUPER MARIO BROS. · +{m.group(1)} MILLION" if LANG == "en" else f"SUPER MARIO BROS. · +{m.group(1)} MILHÕES"

    m = re.match(r"^(\d+)\s*%\s*·\s*JUEGO MÓVIL$", text)
    if m:
        return f"{m.group(1)}% · MOBILE GAMING" if LANG == "en" else f"{m.group(1)} % · JOGO MOBILE"

    m = re.match(r"^(?:(\d{4}) · )?US\$\s*([\d.,]+)\s+MILLONES(?:\s*·\s*3 DÍAS)?$", text)
    if m:
        yr = f"{m.group(1)} · " if m.group(1) else ""
        tail_en = " · 3 DAYS" if "3 DÍAS" in text else ""
        tail_pt = " · 3 DIAS" if "3 DÍAS" in text else ""
        return f"{yr}US$ {m.group(2)} MILLION{tail_en}" if LANG == "en" else f"{yr}US$ {m.group(2)} MILHÕES{tail_pt}"

    return text
