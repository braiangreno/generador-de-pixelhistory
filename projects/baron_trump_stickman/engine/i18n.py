def tr(text, font="press"):
    if not isinstance(text, str) or not text:
        return text
    lang = get_lang()
    if lang == "es":
        return text
    mp = EN_MAP if lang == "en" else (PT_MAP if lang == "pt" else {})
    if text in mp:
        return mp[text]
    m_ch = re.match(r"^CAPÍTULO\s+(\d+)$", text)
    if m_ch:
        return f"CHAPTER {m_ch.group(1)}" if lang == "en" else f"CAPÍTULO {m_ch.group(1)}"
    m_bl = re.match(r"^(\d+)\s+CUADRAS$", text)
    if m_bl:
        return f"{m_bl.group(1)} BLOCKS" if lang == "en" else f"{m_bl.group(1)} QUADRAS"
    m_pr = re.match(r"^(\d+)\s+PAREJAS$", text)
    if m_pr:
        return f"{m_pr.group(1)} PAIRS" if lang == "en" else f"{m_pr.group(1)} PARES"
    return text
